## Fast impurity. For each pair of objects (a, b), a < b, the sign of
## Y[, b] - Y[, a] tells whether a judge prefers a (+1), b (-1) or neither
## (0, tie). Two judges contribute 2 to the Kemeny distance on that pair if
## their signs are opposite and 1 if exactly one of them is a tie, so with
## n+, n- and n0 judges of each kind
##   sum_{k<h} kemd(Y_k, Y_h) = sum_{a<b} [2 n+ n- + n0 (n+ + n-)].
## All the terms are integers, hence the result is the same as
## sum(kemenyd(Y)) bit for bit (and so are the trees).

pairsigns <- function(Y){

  if (anyNA(Y)) {return(NULL)} #missing values: the Kemeny distance matrix is used

  pr <- which(upper.tri(diag(ncol(Y))), arr.ind=TRUE)
  D <- Y[, pr[,2], drop=FALSE] - Y[, pr[,1], drop=FALSE]

  return(list(P = 1*(D>0), N = 1*(D<0)))

} #end function

#--------------------------------------

#sum over all pairs of judges of the Kemeny distances, from the counts P, N
#(vectors, or matrices with one row per subset) of m judges

pairsumkemd <- function(P,N,m){

  Z <- m - P - N

  if (is.matrix(P)) {
    return(rowSums(2*P*N + Z*(P+N)))
  } else {
    return(sum(2*P*N + Z*(P+N)))
  }

} #end function

#--------------------------------------

#impurity of the judges in rows id: identical to rankimpurity(Y[id,])

pairimpurity <- function(Y,PS,id){

  if (is(PS,"NULL")) {return(rankimpurity(Y[id,]))}

  P <- colSums(PS$P[id, , drop=FALSE])
  N <- colSums(PS$N[id, , drop=FALSE])

  return(pairsumkemd(P,N,length(id))/length(id))

} #end function

